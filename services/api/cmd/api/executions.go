package main

import (
 "encoding/json"
 "net/http"
 "strings"
 "github.com/jackc/pgx/v5/pgxpool"
)
type executionRequest struct {
 ID string `json:"id"`
 ProjectID string `json:"projectId"`
 ReleaseID string `json:"releaseId"`
 Scope string `json:"scope"`
 Engine string `json:"engine"`
 EnvironmentID string `json:"environmentId"`
 DeviceID string `json:"deviceId"`
 TestCaseIDs []string `json:"testCaseIds"`
 Snapshot json.RawMessage `json:"snapshot"`
}
func executionsHandler(db *pgxpool.Pool) http.HandlerFunc {
 return func(w http.ResponseWriter,r *http.Request) {
  w.Header().Set("Content-Type","application/json")
  if r.Method==http.MethodPost {
   r.Body=http.MaxBytesReader(w,r.Body,2<<20)
   var e executionRequest
   if json.NewDecoder(r.Body).Decode(&e)!=nil||e.ProjectID==""||e.ReleaseID==""||len(e.TestCaseIDs)==0||!json.Valid(e.Snapshot)||!contains([]string{"full","feature","regression","custom"},e.Scope)||!contains([]string{"playwright","appium","maestro"},e.Engine) {http.Error(w,"invalid execution request",400);return}
   // IDs generated by PostgreSQL; never trust a caller-provided execution identifier.
   ids,_:=json.Marshal(e.TestCaseIDs)
   var id string
   err:=db.QueryRow(r.Context(),`INSERT INTO execution_jobs(id,project_id,release_id,scope,engine,environment_id,device_id,test_case_ids,snapshot) VALUES(gen_random_uuid(),$1,$2,$3,$4,$5,$6,$7,$8) RETURNING id::text`,e.ProjectID,e.ReleaseID,e.Scope,e.Engine,e.EnvironmentID,e.DeviceID,ids,e.Snapshot).Scan(&id)
   if err!=nil {http.Error(w,"could not enqueue execution",500);return}
   w.WriteHeader(http.StatusCreated)
   _=json.NewEncoder(w).Encode(map[string]string{"id":id,"status":"queued"})
   return
  }
  if r.Method!=http.MethodGet {http.Error(w,"method not allowed",405);return}
  if id:=r.URL.Query().Get("id");id!=""{
   rows,err:=db.Query(r.Context(),`SELECT test_case_id,status,duration_ms,logs,artifacts FROM execution_job_results WHERE execution_id=$1::uuid ORDER BY test_case_id`,id)
   if err!=nil{http.Error(w,"results unavailable",500);return};defer rows.Close()
   type result struct{TestCaseID string `json:"testCaseId"`;Status string `json:"status"`;DurationMs int64 `json:"durationMs"`;Logs json.RawMessage `json:"logs"`;Artifacts json.RawMessage `json:"artifacts"`}
   out:=make([]result,0)
   for rows.Next(){var v result;if rows.Scan(&v.TestCaseID,&v.Status,&v.DurationMs,&v.Logs,&v.Artifacts)!=nil{http.Error(w,"scan failed",500);return};out=append(out,v)}
   if rows.Err()!=nil{http.Error(w,"results query failed",500);return}
   _=json.NewEncoder(w).Encode(out);return
  }
  rows,err:=db.Query(r.Context(),`SELECT id::text,project_id,release_id,scope,engine,status,created_at::text FROM execution_jobs ORDER BY created_at DESC LIMIT 100`)
  if err!=nil {http.Error(w,"database query failed",500);return}
  defer rows.Close()
  out:=make([]map[string]string,0)
  for rows.Next(){
   var id,p,rel,scope,engine,status,created string
   if rows.Scan(&id,&p,&rel,&scope,&engine,&status,&created)!=nil {http.Error(w,"scan failed",500);return}
   out=append(out,map[string]string{"id":id,"projectId":p,"releaseId":rel,"scope":scope,"engine":engine,"status":status,"createdAt":created})
  }
  if rows.Err()!=nil {http.Error(w,"query failed",500);return}
  _=json.NewEncoder(w).Encode(out)
 }
}
func contains(xs []string,x string)bool {for _,v:=range xs {if strings.EqualFold(v,x)&&v==x{return true}};return false}
